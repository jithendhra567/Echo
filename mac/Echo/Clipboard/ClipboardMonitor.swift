import AppKit

/// Polls NSPasteboard.general every 500 ms for changes.
/// Runs entirely on the main actor (NSPasteboard and AX APIs are main-thread-only).
@MainActor
final class ClipboardMonitor {
    var onNewClip: ((Clip, ClipStore.SaveResult) -> Void)?

    private let store: ClipStore
    private let settings: AppSettings
    private var lastChangeCount: Int
    private var suppressNext = false
    private var pollerTask: Task<Void, Never>?

    /// Pasteboard flags set by password managers (nspasteboard.org convention).
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init(store: ClipStore, settings: AppSettings) {
        self.store = store
        self.settings = settings
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        pollerTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(500))
                guard !Task.isCancelled else { break }
                self?.poll()
            }
        }
    }

    func stop() {
        pollerTask?.cancel()
        pollerTask = nil
    }

    /// Call immediately before writing to the pasteboard programmatically
    /// so the monitor skips the resulting change event.
    func suppressNextCapture() {
        suppressNext = true
    }

    /// Ignores pasteboard changes for a short window — used during drag sessions.
    func suppressCaptures(for seconds: TimeInterval) {
        suppressUntil = Date().addingTimeInterval(seconds)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Private

    private var suppressUntil: Date?

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if let until = suppressUntil, Date() < until {
            return
        }
        suppressUntil = nil

        if suppressNext {
            suppressNext = false
            return
        }

        guard !settings.isClipboardPaused else { return }
        guard let clip = capture(from: pb) else { return }
        Task { @MainActor in
            let result = await store.save(clip)
            onNewClip?(clip, result)
        }
    }

    private func capture(from pb: NSPasteboard) -> Clip? {
        if settings.skipConcealedContent,
           let types = pb.types,
           Self.concealedTypes.contains(where: types.contains) {
            return nil
        }

        let meta = AppMetadataCapture.capture()

        if let bundle = meta.bundleIdentifier, settings.ignoredApps.contains(bundle) {
            return nil
        }

        // Echo UI copies and drags manage history explicitly — never auto-capture here.
        if let bundle = meta.bundleIdentifier, bundle == Bundle.main.bundleIdentifier {
            return nil
        }

        if let image = NSImage(pasteboard: pb), let data = image.tiffRepresentation {
            guard settings.captureImages else { return nil }
            return makeClip(data: data, type: .image, meta: meta)
        }

        if let urls = pb.readObjects(forClasses: [NSURL.self]) as? [URL],
           let url = urls.first, url.scheme != nil {
            let trimmed = url.absoluteString.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty,
                  let data = trimmed.data(using: .utf8)
            else { return nil }
            guard !AppSettings.isWebsiteIgnored(trimmed) else { return nil }
            return makeClip(data: data, type: .url, meta: meta)
        }

        if let rtf = pb.data(forType: .rtf) {
            return makeClip(data: rtf, type: .richText, meta: meta)
        }

        if let text = pb.string(forType: .string) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty,
                  let data = trimmed.data(using: .utf8)
            else { return nil }
            if AppSettings.isWebsiteIgnored(trimmed) { return nil }
            let type: ClipContentType = AppSettings.host(of: trimmed) != nil ? .url : .plainText
            return makeClip(data: data, type: type, meta: meta)
        }

        return nil
    }

    private func makeClip(data: Data, type: ClipContentType, meta: AppMetadata) -> Clip {
        Clip(
            id: UUID(),
            contentData: data,
            contentType: type,
            sourceAppBundle: meta.bundleIdentifier,
            sourceAppName: meta.localizedName,
            windowTitle: meta.windowTitle,
            createdAt: Date(),
            isPinned: false
        )
    }
}
